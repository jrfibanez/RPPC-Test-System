// Export the data of a seeded database as plain INSERTs for a target that already has the schema (migrations
// applied) but where triggers cannot be switched off (hosted Postgres without superuser, e.g. Supabase).
// Rows keep their ids. Rows the migrations create themselves (roles, permissions, settings) are skipped or mapped by
// role code; the fixed ledger locations and pallet type are replaced by the seed's rows. The audit log is not copied
// (its hash chain starts fresh on the target).
// Usage: DATABASE_OWNER_URL=postgres://…/seeded npx tsx scripts/export-seed-sql.ts > seed.sql
import pg from 'pg';

const SKIP = new Set(['roles', 'permissions', 'role_permissions', 'settings', 'schema_migrations', 'audit_log', 'sessions',
  'login_attempts', 'processed_ops', 'mfa_recovery_codes', 'file_blobs', 'exports']);
const c = new pg.Client({ connectionString: process.env.DATABASE_OWNER_URL });
await c.connect();
await c.query("SET TIME ZONE 'UTC'");
const tables = (await c.query(`SELECT tablename FROM pg_tables WHERE schemaname='public'`)).rows.map((r) => r.tablename as string);
const deps = (await c.query(`SELECT cl.relname AS t, rf.relname AS ref FROM pg_constraint co JOIN pg_class cl ON cl.oid=co.conrelid
  JOIN pg_class rf ON rf.oid=co.confrelid JOIN pg_namespace n ON n.oid=cl.relnamespace
  WHERE co.contype='f' AND n.nspname='public' AND cl.relname <> rf.relname`)).rows;
const order: string[] = [];
const seen = new Set<string>();
const visit = (t: string) => { if (seen.has(t)) return; seen.add(t); for (const d of deps.filter((x) => x.t === t)) visit(d.ref); order.push(t); };
tables.sort().forEach(visit);

const out: string[] = ['-- RPPC demo data (generated by scripts/export-seed-sql.ts)', 'BEGIN;'];
const lit = (s: string) => `$rppc$${s}$rppc$`;
for (const t of order) {
  if (SKIP.has(t)) continue;
  const cols = (await c.query(`SELECT a.attname FROM pg_attribute a JOIN pg_class cl ON cl.oid=a.attrelid JOIN pg_namespace n ON n.oid=cl.relnamespace
    WHERE n.nspname='public' AND cl.relname=$1 AND a.attnum>0 AND NOT a.attisdropped AND a.attgenerated='' ORDER BY a.attnum`, [t])).rows.map((r) => r.attname as string);
  const pk = (await c.query(`SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum = ANY(i.indkey)
    WHERE i.indrelid=$1::regclass AND i.indisprimary`, [t])).rows.map((r) => r.attname as string);
  if (t === 'pallet_types' || t === 'inventory_locations') out.push(`DELETE FROM ${t};`);
  const orderBy = pk.length ? `ORDER BY ${pk.map((k) => `x."${k}"`).join(',')}` : '';
  const json = (await c.query(`SELECT coalesce(json_agg(x ${orderBy}), '[]')::text AS j FROM ${t} x`)).rows[0].j as string;
  if (json === '[]') continue;
  const list = cols.map((x) => `"${x}"`).join(', ');
  if (t === 'user_roles') {
    const codes = (await c.query(`SELECT ur.id, r.code FROM user_roles ur JOIN roles r ON r.id=ur.role_id`)).rows;
    const map = JSON.stringify(Object.fromEntries(codes.map((r) => [r.id, r.code])));
    const sel = cols.map((x) => (x === 'role_id' ? `(SELECT id FROM roles WHERE code = (${lit(map)}::jsonb ->> s.id::text))` : `s."${x}"`)).join(', ');
    out.push(`INSERT INTO user_roles (${list}) SELECT ${sel} FROM json_populate_recordset(NULL::user_roles, ${lit(json)}) s;`);
  } else {
    out.push(`INSERT INTO ${t} (${list}) SELECT ${list} FROM json_populate_recordset(NULL::${t}, ${lit(json)});`);
  }
}
for (const t of ['pallet_movements', 'trip_events']) {
  out.push(`SELECT setval(pg_get_serial_sequence('${t}','id'), COALESCE((SELECT max(id) FROM ${t}), 0) + 1, false);`);
}
out.push(`INSERT INTO audit_log (action, after) VALUES ('seed.demo', '{"note":"demo data loaded for testing"}');`, 'COMMIT;');
console.log(out.join('\n'));
await c.end();
